"""FM1 Quest: the mage of the 3D flight (assets/quest/maga.json: 4 poses, Quest palette indices, 255 = outside) -> a C header:
tools/gen_quest_maga.py build/gen/felucca_qmaga.h
per pose: w*h palette indices, 4 bits each (high nibble first), then a w*h bit mask (1 = opaque). Poses: 0 back, 1 left, 2 right, 3 front."""
import json, sys
from pathlib import Path
src = json.loads((Path(__file__).resolve().parents[1] / "assets" / "quest" / "maga.json").read_text())
data, rows = [], []
for f in src["frames"]:
    w, h, px = f["w"], f["h"], f["px"]
    n = w * h
    assert len(px) == n
    rows.append((w, h, len(data)))
    idx = [0 if v == 255 else v for v in px] + [0]
    data += [(idx[i] << 4) | idx[i + 1] for i in range(0, n, 2)]
    mask = [0 if v == 255 else 1 for v in px] + [0] * (-n % 8)
    data += [sum(b << (7 - j) for j, b in enumerate(mask[i:i + 8])) for i in range(0, len(mask), 8)]
L = ["/* generated by tools/gen_quest_maga.py: the flight's mage, Quest palette indices (4 bits, high nibble first) then a bit mask */", "#pragma once", "#include <stdint.h>",
     "typedef struct { uint8_t w, h; uint16_t off; } qmaga_t;", "enum { QMG_BACK, QMG_LEFT, QMG_RIGHT, QMG_FRONT, QMG_N };",
     f"static const uint8_t QMAGA_DATA[{len(data)}] = {{"]
for i in range(0, len(data), 32):
    L.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
L.append("};")
L.append("static const qmaga_t QMAGA[QMG_N] = {" + ", ".join(f"{{{w}, {h}, {o}}}" for w, h, o in rows) + "};")
Path(sys.argv[1]).write_text("\n".join(L) + "\n")
print(f"quest maga: {len(rows)} poses {[(w, h) for w, h, _ in rows]}, {len(data)} B")
