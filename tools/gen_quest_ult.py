"""The five ults as whole animations: 24 x 24, 3 colours, 4 frames a second for the video's whole length (assets/quest/ult/*.png strips, tools/ult_prep.py).
Coded with a binary range coder (LZMA style, 11-bit probabilities, shift 5): a pixel is 0 / 1 / 2, context = the pixel to the left, the one above and the same
pixel of the frame before. One stream a hero; the player decodes it frame by frame. Order: mage, archer, cleric, knight, red warrior.
tools/gen_quest_ult.py build/gen/felucca_qult.h"""
import json, sys
from pathlib import Path
from PIL import Image
A = Path(__file__).resolve().parents[1] / "assets" / "quest" / "ult"
ORDER = ["mago", "archer", "cleriga", "knight", "guerreiro"]
W = H = 24

class Enc:
    def __init__(s): s.low = 0; s.range = 0xFFFFFFFF; s.cache = 0; s.cache_size = 1; s.out = bytearray()
    def shift_low(s):
        if s.low < 0xFF000000 or s.low >= (1 << 32):
            carry = s.low >> 32
            temp = s.cache
            while True:
                s.out.append((temp + carry) & 0xFF); temp = 0xFF
                s.cache_size -= 1
                if s.cache_size == 0: break
            s.cache = (s.low >> 24) & 0xFF
        s.cache_size += 1
        s.low = (s.low & 0x00FFFFFF) << 8
    def bit(s, probs, i, b):
        p = probs[i]; bound = (s.range >> 11) * p
        if b == 0: s.range = bound; probs[i] = p + ((2048 - p) >> 5)
        else: s.low += bound; s.range -= bound; probs[i] = p - (p >> 5)
        while s.range < (1 << 24): s.range = (s.range << 8) & 0xFFFFFFFF; s.shift_low()
    def finish(s):
        for _ in range(5): s.shift_low()
        return bytes(s.out)

def encode(frames, W=24, H=24, binary=False):
    e = Enc(); probs = [1024] * 128; prev = [0] * (W * H)
    for f in frames:
        for y in range(H):
            for x in range(W):
                l = f[y * W + x - 1] if x else 0
                u = f[(y - 1) * W + x] if y else 0
                v = f[y * W + x]
                if binary:                    # 2 colours: one bit a pixel, six neighbours as the context
                    ul = f[(y - 1) * W + x - 1] if x and y else 0
                    ur = f[(y - 1) * W + x + 1] if y and x < W - 1 else 0
                    pn = prev[y * W + x + 1] if x < W - 1 else 0
                    e.bit(probs, l | u << 1 | prev[y * W + x] << 2 | ul << 3 | ur << 4 | pn << 5, v)
                    continue
                c = (l * 3 + u) * 3 + prev[y * W + x]
                e.bit(probs, c * 2, 0 if v == 0 else 1)
                if v: e.bit(probs, c * 2 + 1, 0 if v == 1 else 1)
        prev = f
    return e.finish()

STEP = {"mago": 4, "archer": 4}               # (their frames are noise: half of them)
import os
DIM = int(os.environ.get("ULT_DIM", "48"))                 # 0.3: 48 x 48 (5 LCD px a cell full screen, 1 in the 48 px band); the 0.21 had 32 x 32
GIF_STEP = 2                                 # a .gif replaces the strip: every 2nd frame, DIM x DIM, 2 colours (dark 0, light 1)
pals, nfr, blobs, offs, dims, bins = [], [], bytearray(), [0], [], []
for n in ORDER:
    f = A / (n + ".png")
    g = A / (n + ".gif")
    if g.exists():
        gi = Image.open(g)
        frames = []
        cols = None
        for i in range(0, gi.n_frames, STEP.get(n, 2 if gi.n_frames >= 200 else 1)):
            gi.seek(i)
            im = gi.convert("L").resize((DIM, DIM), Image.LANCZOS)
            frames.append([1 if p >= 128 else 0 for p in im.getdata()])
        z = encode(frames, DIM, DIM, True)
        blobs += z
        offs.append(len(blobs))
        pals.append([((5 >> 3) << 11) | ((7 >> 2) << 5) | (10 >> 3), ((234 >> 3) << 11) | ((247 >> 2) << 5) | (255 >> 3), 0])
        nfr.append(len(frames)); dims.append((DIM, DIM)); bins.append(1)
        continue
    if not f.exists():
        pals.append([0, 0, 0]); nfr.append(0); offs.append(len(blobs)); dims.append((24, 24)); bins.append(0); continue
    im = Image.open(f).convert("RGB")
    cols = sorted({c for c in im.getdata()}, key=lambda c: c[0] * 3 + c[1] * 6 + c[2])
    cols = (cols + [(0, 0, 0)] * 3)[:3]
    idx = {c: i for i, c in enumerate(cols)}
    n_fr = im.height // H
    data = [idx.get(c, 0) for c in im.getdata()]
    frames = [data[i * W * H:(i + 1) * W * H] for i in range(n_fr)]
    z = encode(frames)
    blobs += z
    offs.append(len(blobs))
    pals.append([((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3) for c in cols])
    nfr.append(n_fr); dims.append((24, 24)); bins.append(0)
import json as _j
FPS = _j.loads((A / "ult.json").read_text())["mago"]["fps"] if (A / "ult.json").exists() else 3
L = ["/* generated by tools/gen_quest_ult.py */", "#pragma once", "#include <stdint.h>", f"#define QULT_FPS {FPS}",
     "static const uint16_t QULT_PAL[5][3] = {" + ",".join("{" + ",".join(str(c) for c in p) + "}" for p in pals) + "};",
     "static const uint8_t QULT_N[5] = {" + ",".join(str(n) for n in nfr) + "};",
     "static const uint8_t QULT_W[5] = {" + ",".join(str(d[0]) for d in dims) + "}, QULT_H[5] = {" + ",".join(str(d[1]) for d in dims) + "}, QULT_B[5] = {" + ",".join(map(str, bins)) + "};",
     "static const uint16_t QULT_ZO[6] = {" + ",".join(str(o) for o in offs) + "};",
     f"static const uint8_t QULT_Z[{max(1, len(blobs))}] = {{" + (",".join(str(b) for b in blobs) if blobs else "0") + "};"]
Path(sys.argv[1]).write_text("\n".join(L) + "\n")
print(f"quest ult: {len(blobs)} B for {sum(nfr)} frames")
